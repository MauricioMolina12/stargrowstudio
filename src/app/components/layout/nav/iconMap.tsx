/** Mapa de nombres (string desde Sanity o config) a componentes de icono. */
const ICONS: Record<string, LucideIcon> = {
  Aperture,
  BarChart3,
  Building2,
  Camera,
  Code,
  Database,
  FolderKanban,
  Glasses,
  HelpCircle,
  History,
  Instagram,
  LayoutTemplate,
  Lightbulb,
  MonitorSmartphone,
  Network,
  Package,
  Palette,
  PartyPopper,
  Pencil,
  PenTool,
  Rocket,
  Route,
  ScrollText,
  Share2,
  Smartphone,
  Sparkles,
  TrendingUp,
  Users,
  Wand2,
  Workflow,
  Wrench,
};

/** Devuelve el componente de icono para un nombre dado (fallback a Sparkles). */
export function getIcon(name?: string): LucideIcon {
  if (name && ICONS[name]) return ICONS[name];
  return Sparkles;
}
